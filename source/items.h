// Bag tabs: 0 = all, 1..5 match ItemDef::cat.
enum ItemCat : uint8_t {
  CAT_POTION = 1,
  CAT_SCROLL = 2,
  CAT_WAND = 3,
  CAT_GEAR = 4,
  CAT_MISC = 5,
};

struct ItemDef {
  const char* name;
  const char* desc;
  uint8_t kind;
  uint8_t cat;
  int8_t power;
  uint8_t max_charge;
  int16_t sprite;
};

extern const ItemDef ITEM_DEFS[IT_COUNT];

inline const ItemDef& item_def(uint8_t id) {
  return ITEM_DEFS[id < IT_COUNT ? id : 0];
}
