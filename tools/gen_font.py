#!/usr/bin/env python3
"""Build a 3DS-friendly bitmap font atlas from the UI strings in source/.

Scans source/*.cpp and source/*.h for every non-ASCII character, renders those
plus printable ASCII with a 12px OFL pixel font (Ark Pixel), and writes:

  gfx/font.png          white glyphs, alpha mask
  gfx/font.t3s          tex3ds input
  source/font_glyphs.h  codepoint -> atlas rect + metrics

Re-run after adding new UI strings:  tools/venv/bin/python tools/gen_font.py
"""

import glob
import os
import sys
from math import ceil

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_PATH = os.path.join(ROOT, "tools/fonts/fusion-pixel-12px-monospaced-zh_hans.ttf")
SIZE = 12
CELL = 16
COLS = 32

if not os.path.exists(FONT_PATH):
    sys.exit(f"missing font: {FONT_PATH} (see tools/prepare-assets.sh)")

chars = {chr(c) for c in range(32, 127)}
chars |= set("，。！？：；、“”‘’（）【】《》…—·％＋－×÷")
for path in glob.glob(os.path.join(ROOT, "source", "*.cpp")) + glob.glob(
    os.path.join(ROOT, "source", "*.h")
):
    with open(path, encoding="utf-8") as f:
        for ch in f.read():
            if ord(ch) > 127:
                chars.add(ch)

try:
    from fontTools.ttLib import TTFont
    cmap = TTFont(FONT_PATH).getBestCmap()
    missing = sorted(ch for ch in chars if ord(ch) not in cmap)
    if missing:
        print("WARNING: font has no glyph for: " + "".join(missing))
except ImportError:
    pass

font = ImageFont.truetype(FONT_PATH, SIZE)
ascent, descent = font.getmetrics()
ordered = sorted(chars, key=ord)
rows = ceil(len(ordered) / COLS)
W, H = COLS * CELL, rows * CELL

mask = Image.new("L", (W, H), 0)
draw = ImageDraw.Draw(mask)

glyphs = []
for i, ch in enumerate(ordered):
    cx = (i % COLS) * CELL
    cy = (i // COLS) * CELL
    try:
        bbox = font.getbbox(ch)
        adv = int(round(font.getlength(ch)))
        draw.text((cx, cy + ascent), ch, font=font, fill=255, anchor="ls")
    except Exception:
        continue
    xoff, yoff = bbox[0], bbox[1]
    gw, gh = bbox[2] - bbox[0], bbox[3] - bbox[1]
    glyphs.append((ord(ch), cx + xoff, cy + yoff, gw, gh, xoff, yoff, adv))

mask = mask.point(lambda v: 255 if v >= 128 else 0)
rgba = Image.new("RGBA", (W, H), (255, 255, 255, 0))
rgba.putalpha(mask)
rgba.save(os.path.join(ROOT, "gfx/font.png"))

with open(os.path.join(ROOT, "gfx/font.t3s"), "w") as f:
    f.write("-f rgba8888\nfont.png\n")

with open(os.path.join(ROOT, "source/font_glyphs.h"), "w", encoding="utf-8") as f:
    f.write("// Generated by tools/gen_font.py - do not edit.\n")
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write(f"#define FONT_ATLAS_W {W}\n#define FONT_ATLAS_H {H}\n")
    f.write(f"#define FONT_LINE_H {SIZE + 1}\n")
    f.write("#define FONT_ASCENT %d\n\n" % ascent)
    f.write("struct FontGlyph { uint32_t cp; uint16_t x, y, w, h;"
            " int8_t xoff, yoff; uint8_t adv; };\n")
    f.write("static const FontGlyph FONT_GLYPHS[] = {\n")
    for cp, x, y, w, h, xo, yo, adv in glyphs:
        f.write(f"  {{0x{cp:04X}, {x}, {y}, {w}, {h}, {xo}, {yo}, {adv}}},\n")
    f.write("};\n")
    f.write("#define FONT_GLYPH_COUNT (int)(sizeof(FONT_GLYPHS)/sizeof(FONT_GLYPHS[0]))\n")

print(f"font atlas: {W}x{H}, {len(glyphs)} glyphs")
